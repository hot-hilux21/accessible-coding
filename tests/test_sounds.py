"""The interface sounds are bundled, small, and actually wired up.

The tones are generated by scripts/make_sounds.py, not downloaded, so they
have to be in the repository and they have to be playable. A sound the app
asks for but never ships is silence plus a 404 in the console, and a sound
that ships but is never asked for is dead weight.
"""
import json
import unittest
import wave
from pathlib import Path

import accessible_ide
from accessible_ide import routes

ROOT = Path(accessible_ide.__file__).resolve().parent
AUDIO = ROOT / 'static' / 'audio'
APP_JS = (ROOT / 'static' / 'js' / 'app.js').read_text(encoding='utf-8')

# The four moments the app makes a noise, and the file each one plays.
SOUNDS = ('press', 'success', 'error', 'pause')


class SoundFilesTest(unittest.TestCase):
    def test_every_sound_is_bundled(self):
        for name in SOUNDS:
            self.assertTrue((AUDIO / (name + '.wav')).is_file(),
                            '%s.wav is missing from static/audio' % name)

    def test_every_sound_is_a_small_mono_wav(self):
        for name in SOUNDS:
            path = AUDIO / (name + '.wav')
            with wave.open(str(path), 'rb') as handle:
                self.assertEqual(handle.getnchannels(), 1, name)
                self.assertEqual(handle.getsampwidth(), 2, name)
                self.assertEqual(handle.getframerate(), 22050, name)
                # Long enough to hear, short enough not to get in the way.
                duration = handle.getnframes() / 22050.0
                self.assertGreater(duration, 0.02, name)
                self.assertLess(duration, 0.6, name)
            # Bundled with the app, so every kilobyte is the reader's disk.
            self.assertLess(path.stat().st_size, 20 * 1024, name)

    def test_the_app_asks_for_each_sound(self):
        for name in SOUNDS:
            self.assertIn("playSound('%s')" % name, APP_JS,
                          'nothing plays %s.wav' % name)


class SoundSettingTest(unittest.TestCase):
    def test_sound_is_on_by_default(self):
        self.assertIs(routes.DEFAULT_CONFIG['sound_enabled'], True)

    def test_sound_is_a_known_settings_key(self):
        self.assertIs(routes.CONFIG_TYPES['sound_enabled'], bool)

    def test_sound_can_be_saved_and_read_back(self):
        config = routes.DEFAULT_CONFIG.copy()
        config['sound_enabled'] = False
        self.assertIs(config['sound_enabled'], False)

    def test_the_switch_has_words_in_every_language(self):
        for code in ('en', 'fr', 'es', 'hi', 'ar', 'uk'):
            path = ROOT / 'i18n' / (code + '.json')
            data = json.loads(path.read_text(encoding='utf-8'))
            for key in ('group.sound', 'sound.label', 'sound.help'):
                self.assertTrue(data.get(key), '%s is missing %s' % (code, key))


if __name__ == '__main__':
    unittest.main()